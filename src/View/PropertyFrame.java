    private void setData(List<Property> pros){
        for (Property pro : pros){
            defaultTableModel.addRow(new Object[]{pro.getIdPro(),pro.getNamePro(),pro.getCategoryPro(),pro.getPositionPro(),pro.getValuePro()});
            
        }
    }
    private void setTableModel(){
        defaultTableModel = new DefaultTableModel(){
            //Khong cho sua cot 0(cot id)
            @Override
            public boolean isCellEditable(int row, int column){
                return column != 0;
            }
        };
        defaultTableModel.addColumn("ID");
        defaultTableModel.addColumn("Name");
        defaultTableModel.addColumn("Category");
        defaultTableModel.addColumn("Position");
        defaultTableModel.addColumn("Value");
        jTableProperty.setModel(defaultTableModel);
        jTableProperty.getTableHeader().setReorderingAllowed(false);    //Tat chuc nang thay doi vi tri cot
        jTableProperty.getTableHeader().setResizingAllowed(false);      //Tat chuc nang thay doi kich thuoc cot  
        jTableProperty.getColumnModel().getColumn(0).setPreferredWidth(50);  
        jTableProperty.getColumnModel().getColumn(1).setPreferredWidth(150); 
        jTableProperty.getColumnModel().getColumn(2).setPreferredWidth(150);
        jTableProperty.getColumnModel().getColumn(3).setPreferredWidth(150);
        jTableProperty.getColumnModel().getColumn(4).setPreferredWidth(150);
        defaultTableModel.addTableModelListener((TableModelEvent e) -> {
            if (e.getType() == TableModelEvent.UPDATE){
                int row = e.getFirstRow();
                int col = e.getColumn();
                //ALL_COLUMNS = thay doi toan bo gia tri cua bang (refresh)
                if (col != TableModelEvent.ALL_COLUMNS){
                    //Goi ham Update database
                    int id = (int)defaultTableModel.getValueAt(row, 0);
                        String name = (String) defaultTableModel.getValueAt(row, 1);
                        String des = (String) defaultTableModel.getValueAt(row, 2);
                        Room updateRoom = new Room(id,name,des);
                        Request o = new Request(Request.ViewType.ROOM,Request.CommandType.UPDATE,updateRoom);
                        System.out.println(o.toString());
                        clc.sendRequest(o);
                }
            }
        });
    }
    
    public PropertyFrame(Room room){
        initComponents();
        setTableModel();
        Title.setText("Phong " + room.getNameRoom());
        Socket mySocket = clc.openConnection();
        clc.sendRequest(new Request(Request.ViewType.PROPERTY,Request.CommandType.GET_ALL,room));
        List<Property> pros = (List<Property>) clc.receiveData();
        setData(pros);
        
        
    }
