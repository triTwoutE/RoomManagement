    public RoomFrame() {
        initComponents();
        setTableModel();
        Socket mySocket = clc.openConnection();
        //Request Get All Room:
        Request request = new Request(Request.ViewType.ROOM,Request.CommandType.GET_ALL,null);
        clc.sendRequest(request);
        List<Room> rooms = (List<Room>) clc.receiveData();
        setData(rooms);
        
        //Chuc nang sua bang truc tiep
        defaultTableModel.addTableModelListener(new TableModelListener(){
            @Override
            public void tableChanged(TableModelEvent e) {
                if (e.getType() == TableModelEvent.UPDATE){
                    int row = e.getFirstRow();
                    int col = e.getColumn();
                    if (col != TableModelEvent.ALL_COLUMNS){
                        int id = (int)defaultTableModel.getValueAt(row, 0);
                        String name = (String) defaultTableModel.getValueAt(row, 1);
                        String des = (String) defaultTableModel.getValueAt(row, 2);
                        Room updateRoom = new Room(id,name,des);
                        Request o = new Request(Request.ViewType.ROOM,Request.CommandType.UPDATE,updateRoom);
                        System.out.println(o.toString());
                        clc.sendRequest(o);
                    }
                }
                }
            
        });
        
        
        
    }

