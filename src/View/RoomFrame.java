    private void setData(List<Room> rooms){ 
        for (Room room : rooms){
            defaultTableModel.addRow(new Object[]{room.getIdRoom(),room.getNameRoom(),room.getDescriptionRoom()});
            
        }
    }
    private void setTableModel(){
        defaultTableModel = new DefaultTableModel(){
            //Khong cho sua cot 0(cot id)
            @Override
            public boolean isCellEditable(int row, int column){
                return column != 0;
            }
        };
        defaultTableModel.addColumn("ID");
        defaultTableModel.addColumn("Name");
        defaultTableModel.addColumn("Description");
        jTableRoom.setModel(defaultTableModel);
        jTableRoom.getTableHeader().setReorderingAllowed(false);    //Tat chuc nang thay doi vi tri cot
        jTableRoom.getTableHeader().setResizingAllowed(false);      //Tat chuc nang thay doi kich thuoc cot  
        jTableRoom.getColumnModel().getColumn(0).setPreferredWidth(50);  
        jTableRoom.getColumnModel().getColumn(1).setPreferredWidth(150); 
        jTableRoom.getColumnModel().getColumn(2).setPreferredWidth(250);
        
    }
